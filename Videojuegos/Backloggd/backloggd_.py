def obtener_slug(nombre: str) -> str:
    """Devuelve el slug exacto desde EXCEPCIONES_BACKLOGGD o lo genera desde el título."""
    if nombre in EXCEPCIONES_BACKLOGGD:
        return EXCEPCIONES_BACKLOGGD[nombre]
    
### BLOQUE GENERADO POR IA , GEMINI-5 ##
    # Normalizar el texto para generar un slug
    texto = unicodedata.normalize("NFKD", nombre)
    texto = texto.encode("ascii", "ignore").decode("ascii").lower()
    texto = texto.replace("&", " ")
    texto = re.sub(r"[^a-z0-9\s-]", "", texto)
    texto = re.sub(r"[\s-]+", "-", texto).strip("-")
    return texto

