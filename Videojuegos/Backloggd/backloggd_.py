def scrapear_videojuego(nombre: str, headers: dict) -> dict:
    """Consulta la ficha de un videojuego en Backloggd y devuelve un diccionario estructurado."""
    slug = obtener_slug(nombre)
    url = f"https://backloggd.com/games/{slug}/"

    respuesta = requests.get(url, headers=headers, timeout=10)
    respuesta.raise_for_status()

    soup = BeautifulSoup(respuesta.text, "html.parser")
    texto = soup.get_text(" ", strip=True)

    # Valoración media
    if "Avg Rating" in texto:
        valoracion = texto.split("Avg Rating", 1)[1].split()[0]
    else:
        valoracion = "N/A"

    # Duración media en minutos
    elem_duracion = soup.find(class_="mb-0 stat-value element-revealed")
    if elem_duracion:
        duracion_limpia = elem_duracion.text.strip()
        valor_sin_unidad = duracion_limpia[:-1].strip()
        duracion_media = (
            0 if valor_sin_unidad in ("", "-") else float(valor_sin_unidad) * 60
        )
    else:
        duracion_media = "N/A"

    # Géneros
    contenedor_generos = soup.find("div", class_="col-auto col-md ml-auto my-auto")
    generos = []
    if contenedor_generos:
        generos = [
            g.get_text(strip=True)
            for g in contenedor_generos.find_all("a", class_="game-details-value")
            if g.get_text(strip=True)
        ]

    # Plataformas
    contenedor_plataformas = soup.find("div", id="game-page-platforms")
    plataformas = []
    if contenedor_plataformas:
        plataformas = [
            p.get_text(strip=True)
            for p in contenedor_plataformas.find_all("a", class_="game-page-platform")
            if p.get_text(strip=True)
        ]

    return {
        "titulo": nombre,
        "Valoración": valoracion,
        "duracion_min": duracion_media,
        "generos": generos,
        "Plataformas": plataformas,
    }


def guardar_en_json(datos: list, ruta_archivo: str = "videojuegos.json") -> None:
    """Guarda la lista de videojuegos en un archivo JSON."""
    with open(ruta_archivo, "w", encoding="utf-8") as archivo:
        json.dump(datos, archivo, ensure_ascii=False, indent=4)
    print(f"Guardados {len(datos)} registros en '{ruta_archivo}'.")


def ejecutar_scraper(videojuegos: list, ruta_salida: str = "videojuegos.json") -> list:
    """Ejecuta el scraping para una lista de videojuegos y guarda el resultado en JSON."""
    headers = {
        "User-Agent": (
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
            "AppleWebKit/537.36 (KHTML, like Gecko) "
            "Chrome/124.0.0.0 Safari/537.36"
        )
    }

    resultados = []
    titulos_unicos = list(dict.fromkeys(videojuegos))

    for nombre in titulos_unicos:
        try:
            registro = scrapear_videojuego(nombre, headers)
            resultados.append(registro)
            print(
                f"[OK] {nombre} -> Nota: {registro['Valoración']} | "
                f"Plataformas: {len(registro['Plataformas'])}"
            )
            time.sleep(0.5)
        except requests.RequestException as e:
            print(f"[ERROR] {nombre} -> {e}")
            resultados.append({
                "titulo": nombre,
                "Valoración": "N/A",
                "duracion_min": "N/A",
                "generos": [],
                "Plataformas": [],
            })

    guardar_en_json(resultados, ruta_salida)
    return resultados


